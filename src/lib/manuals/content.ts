export function manualsByCategory(id: ManualCategoryId): Manual[] {
  return MANUALS.filter((manual) => manual.category === id);
}

export function findManual(slug: string): Manual | undefined {
  return MANUALS.find((manual) => manual.slug === slug);
}

export function findCategory(id: ManualCategoryId): ManualCategory {
  return MANUAL_CATEGORIES.find((category) => category.id === id)!;
}

/** Case-insensitive search over title, summary and step text. */
export function searchManuals(query: string): Manual[] {
  const tokens = query.toLowerCase().split(/\s+/).filter(Boolean);
  if (tokens.length === 0) return MANUALS;
  return MANUALS.filter((manual) => {
    const haystack = [manual.title, manual.summary, ...manual.steps.flatMap((step) => [step.title, step.detail, ...(step.callouts ?? [])])]
      .join(" ")
      .toLowerCase();
    return tokens.every((token) => haystack.includes(token));
  });
}
